/* ============================================================
 * ライフパスを 1–9 に還元(マスター数は加算)
 * ============================================================ */

function reduceLP(n) {
  let x = n;
  while (x > 9) {
    x = String(x).split('').reduce((a, b) => a + Number(b), 0);
  }
  return x;
}

