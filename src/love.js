/* ============================================================
 * アーケタイプの index 算出
 *  - 太陽星座のエレメント(火/地/風/水) → 4 系統(0..3)
 *  - ライフパス(マスター数還元) % 3 → サブ index(0..2)
 *  - archetype index = element * 3 + sub
 * ============================================================ */

const ELEMENT_BASE = {
  '火': 0, '地': 3, '風': 6, '水': 9,
  Fire: 0, Earth: 3, Air: 6, Water: 9
};

const MOON_ACTIONS = Object.values(ACTIONS_BY_MOON);

function actionForMoon(mp) {
  if (!mp) return MOON_ACTIONS[0];
  const idx = Math.min(7, Math.max(0, Math.floor((mp.phase ?? 0) * 8)));
  return MOON_ACTIONS[idx];
}

function pickArchetypeIndex(sun, lp) {
  const base = ELEMENT_BASE[sun?.element] ?? 0;
  const r = reduceLP(lp);
  const sub = (r - 1) % 3;    // lp 1 → sub 0, lp 2 → sub 1, lp 3 → sub 2, lp 4 → sub 0…
  return base + sub;
}

/* ============================================================
 * 相性の良いアーケタイプ群 → 「気になる人と相性診断へ」CTA に使う
 * ============================================================ */

function matchesByName(matches) {
  return matches.map(name => LOVE_ARCHETYPES.find(a => a.name === name)).filter(Boolean);
}

/* ============================================================
 * 公開関数:既存 ctx から恋愛診断を組み立てる
 *
 * @param {object} ctx — render() で currentContext に入っているもの
 *   必須フィールド: sun{element,name,symbol}, lp, py, mp{name}
 * @returns {{
 *   archetype: object,
 *   phase: { label: string, text: string },
 *   action: string,
 *   matches: object[],
 *   summaryLine: string
 * }}
 * ============================================================ */

export function computeLove(ctx) {
  if (!ctx) throw new Error('[love] context required');

  const idx = pickArchetypeIndex(ctx.sun, ctx.lp);
  const archetype = LOVE_ARCHETYPES[idx];

  const phase = PHASE_BY_PY[reduceLP(ctx.py)] ?? PHASE_BY_PY[1];
  const action = actionForMoon(ctx.mp);
  const matches = matchesByName(archetype.matches);

  const summaryLine =
    `${archetype.name} — ${archetype.catch}。今は「${phase.label}」を歩いています。`;

  return { archetype, phase, action, matches, summaryLine };
}
